def main() -> int:
    rows = re.findall(r"^\| ((?:FR|NFR)-[A-Z0-9]+-\d+) \| ([^|]+) \| [^|]* \| (P\d) \|", TRACKER.read_text(), re.M)
    ids = [r[0] for r in rows]
    missing = [i for i in ids if i not in S]
    extra = [i for i in S if i not in ids]
    if missing or extra:
        print("missing:", missing, "extra:", extra)
        return 1
    counts = {FULL: 0, PART: 0, NONE: 0}
    lines = []
    for fid, name, prio in rows:
        cov, docs, strat = S[fid]
        counts[cov] += 1
        d = ", ".join(f"[{x.split('_')[0].title()}]({DOCFILE[x]})" for x in docs) or "-"
        lines.append(f"| {fid} | {name.strip()} | {prio} | {cov} | {strat} | {d} |")
    gaps = [(fid, name.strip(), prio, S[fid]) for fid, name, prio in rows if S[fid][0] != FULL]
    out = [
        "# Architecture Coverage Review", "",
        "**Generated by** `02_ARCHITECTURE/tools/coverage.py` from `FEATURE_TRACKER.md`. Do not edit by hand; edit the script and re-run.", "",
        f"**Features reviewed:** {len(rows)} | **DEFINED:** {counts[FULL]} | **PARTIAL:** {counts[PART]} | **NO STRATEGY:** {counts[NONE]}", "",
        "| Coverage | Meaning |", "|---|---|",
        "| DEFINED | The architecture says which component, data and interface implement it |",
        "| PARTIAL | The structure exists, but a named design element or external input is missing |",
        "| NO STRATEGY | No implementation strategy. Reason given |", "",
        "**Coverage is a design statement only. Every feature is still NOT IMPLEMENTED.**", "",
        "## Features without a full strategy", "",
        "| Feature | Name | Priority | Coverage | Gap |", "|---|---|---|---|---|",
        *[f"| {g[0]} | {g[1]} | {g[2]} | {g[3][0]} | {g[3][2]} |" for g in gaps], "",
        f"**P0 items not fully defined:** {', '.join(g[0] for g in gaps if g[2] == 'P0') or 'none'}", "",
        "## All features", "",
        "| Feature | Name | Priority | Coverage | Strategy | Docs |", "|---|---|---|---|---|---|",
        *lines, "",
    ]
    OUT.write_text("\n".join(out))
    print(f"{len(rows)} features: {counts}")
    print("P0 not fully defined:", [g[0] for g in gaps if g[2] == "P0"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
